hl.monitor({ output = "DP-2", mode = "2560x1440@179.877", position = "0x0", scale = 1, vrr = 0, bitdepth = 10 })
hl.monitor({ output = "HDMI-A-1", mode = "1920x1080@60.000", position = "2560x360", scale = 1 })
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "auto" })

-------------------
---- АВТОЗАПУСК ----
-------------------
-- Noctalia стартует от graphical-session.target.
-- Под UWSM его поднимает UWSM; в обычной сессии «Hyprland» — передаём окружение
-- в systemd и запускаем hyprland-session.target (см. home/desktop/hyprland.nix).
local plainSession = "! uwsm check is-active >/dev/null 2>&1"
hl.on("hyprland.start", function()
	hl.exec_cmd(plainSession .. " && dbus-update-activation-environment --systemd --all"
		.. " && systemctl --user start hyprland-session.target")
	hl.exec_cmd("hyprctl setcursor Bibata-Modern-Classic 20")
end)
hl.on("hyprland.shutdown", function()
	hl.exec_cmd(plainSession .. " && systemctl --user stop hyprland-session.target")
end)

-- Цвета и тема от Noctalia (~/.config/hypr/noctalia.lua генерирует он сам)
local noctalia_ok, noctalia = pcall(function() return require("noctalia") end)
if noctalia_ok then noctalia.apply_theme() end

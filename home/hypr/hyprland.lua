-- Файлы, которые генерирует DMS в ~/.config/hypr/dms/ (цвета под обои, мониторы, правила окон).
-- pcall — чтобы конфиг не падал, пока DMS их ещё не создал.
local function dms(name)
	local ok, err = pcall(require, "dms." .. name)
	if not ok and not tostring(err):find("not found") then
		hl.notification.create({ text = "dms." .. name .. ": " .. tostring(err), timeout = 8000 })
	end
end


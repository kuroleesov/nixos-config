-- DMS стартует как systemd-сервис от graphical-session.target.
-- Под UWSM его поднимает UWSM; в обычной сессии «Hyprland» — передаём окружение
-- в systemd и запускаем hyprland-session.target (см. home/hyprland.nix).
local plainSession = "! uwsm check is-active >/dev/null 2>&1"
hl.on("hyprland.start", function()
	hl.exec_cmd(plainSession .. " && dbus-update-activation-environment --systemd --all"
		.. " && systemctl --user start hyprland-session.target")
end)
hl.on("hyprland.shutdown", function()
	hl.exec_cmd(plainSession .. " && systemctl --user stop hyprland-session.target")
end)

